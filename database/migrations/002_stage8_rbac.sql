-- AccessMate Stage 8 — RBAC, security, and audit migration.
-- Executed by backend/scripts/migrate.js inside a transaction.
-- Preconditions: public.users(id), public.documents(id,user_id), public.activity_logs exist.
-- ADDITIVE ONLY — no DROP TABLE, DROP COLUMN, TRUNCATE, or DELETE.

-- 1. Extend users table with role, status, last_login, preferences
ALTER TABLE public.users
  ADD COLUMN IF NOT EXISTS role VARCHAR(20) NOT NULL DEFAULT 'user'
    CONSTRAINT users_role_check CHECK (role IN ('user','staff','admin','super_admin')),
  ADD COLUMN IF NOT EXISTS status VARCHAR(20) NOT NULL DEFAULT 'active'
    CONSTRAINT users_status_check CHECK (status IN ('active','suspended','deactivated')),
  ADD COLUMN IF NOT EXISTS last_login_at TIMESTAMPTZ,
  ADD COLUMN IF NOT EXISTS preferences JSONB NOT NULL DEFAULT '{}'::jsonb;

CREATE INDEX IF NOT EXISTS idx_users_role   ON public.users(role);
CREATE INDEX IF NOT EXISTS idx_users_status ON public.users(status);

-- 2. JWT revocation blocklist
CREATE TABLE IF NOT EXISTS public.revoked_tokens (
  jti        VARCHAR(36) PRIMARY KEY,
  expires_at TIMESTAMPTZ NOT NULL,
  revoked_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_revoked_expires ON public.revoked_tokens(expires_at);

-- 3. Refresh tokens
CREATE TABLE IF NOT EXISTS public.refresh_tokens (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  token_hash VARCHAR(255) NOT NULL UNIQUE,
  expires_at TIMESTAMPTZ NOT NULL,
  revoked_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_rt_user    ON public.refresh_tokens(user_id);
CREATE INDEX IF NOT EXISTS idx_rt_expires ON public.refresh_tokens(expires_at);

-- 4. Password reset tokens
CREATE TABLE IF NOT EXISTS public.password_reset_tokens (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  token_hash VARCHAR(255) NOT NULL,
  expires_at TIMESTAMPTZ NOT NULL,
  used_at    TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_prt_user ON public.password_reset_tokens(user_id);

-- 5. Staff permission overrides
CREATE TABLE IF NOT EXISTS public.staff_permissions (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  permission VARCHAR(80) NOT NULL,
  granted    BOOLEAN NOT NULL DEFAULT TRUE,
  granted_by BIGINT NOT NULL REFERENCES public.users(id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE(user_id, permission)
);
CREATE INDEX IF NOT EXISTS idx_sp_user ON public.staff_permissions(user_id);

-- 6. Account invitations (staff/admin provisioning)
CREATE TABLE IF NOT EXISTS public.account_invitations (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email       VARCHAR(255) NOT NULL,
  role        VARCHAR(20)  NOT NULL,
  token_hash  VARCHAR(255) NOT NULL,
  invited_by  BIGINT NOT NULL REFERENCES public.users(id),
  expires_at  TIMESTAMPTZ NOT NULL,
  accepted_at TIMESTAMPTZ,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_inv_email ON public.account_invitations(email);

-- 7. Rich audit log (separate from legacy activity_logs)
CREATE TABLE IF NOT EXISTS public.audit_logs (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id    BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
  actor_role  VARCHAR(20),
  action      VARCHAR(120) NOT NULL,
  target_type VARCHAR(60),
  target_id   BIGINT,
  outcome     VARCHAR(20) NOT NULL DEFAULT 'success'
    CONSTRAINT audit_outcome_check CHECK (outcome IN ('success','failure','denied')),
  details     JSONB NOT NULL DEFAULT '{}'::jsonb,
  ip_address  INET,
  request_id  VARCHAR(36),
  created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_audit_actor  ON public.audit_logs(actor_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_audit_action ON public.audit_logs(action, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_audit_created ON public.audit_logs(created_at DESC);
